#!/usr/bin/env node
/**
 * Generates the route manifest consumed by the `seo-routing` Netlify edge function.
 *
 * - App routes: every `trailRoute('...')` path in src/App.tsx. Routes rendered as
 *   <Navigate> are treated as pass-through (their 301 lives in public/_redirects).
 * - Pass-through routes: every 301/302 source in public/_redirects, so the edge
 *   function never 404s or double-redirects a path the static rules already handle.
 *
 * Output: netlify/edge-functions/lib/known-routes.generated.ts (committed; rerun on build).
 *
 * `--dist` (run after `vite build`, before prerender overwrites dist/index.html):
 * - dist/404.html ← raw SPA shell, so Netlify serves real 404s that still render <NotFound />
 * - dist/_redirects: the blanket `/* /index.html 200` rewrite is replaced by one rewrite per
 *   app route, so unknown paths and missing files fall through to 404.html with status 404.
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..');
const APP_PATH = path.join(ROOT, 'src/App.tsx');
const REDIRECTS_PATH = path.join(ROOT, 'public/_redirects');
const OUT_PATH = path.join(ROOT, 'netlify/edge-functions/lib/known-routes.generated.ts');
const DIST_DIR = path.join(ROOT, 'dist');
const SPA_FALLBACK_RULE = /^\/\*\s+\/index\.html\s+200\s*$/m;

const withSlash = (p) => (p === '/' || p.endsWith('/') || p.endsWith('*') ? p : `${p}/`);

/** @returns {{ appRoutes: string[], passThroughRoutes: string[] }} */
export function extractRoutePatterns(appSource, redirectsSource) {
    const appRoutes = new Set();
    const passThroughRoutes = new Set();

    for (const line of appSource.split('\n')) {
        const m = line.match(/path=\{trailRoute\('([^']+)'\)\}/);
        if (!m || m[1] === '/' || m[1] === '*') continue;
        const target = line.includes('element={<Navigate') ? passThroughRoutes : appRoutes;
        target.add(withSlash(m[1]));
    }

    for (const raw of redirectsSource.split('\n')) {
        const line = raw.trim();
        if (!line || line.startsWith('#')) continue;
        const [from, , status] = line.split(/\s+/);
        if (!from || from === '/*' || !/^30[12]!?$/.test(status ?? '')) continue;
        passThroughRoutes.add(withSlash(from));
    }

    return {
        appRoutes: [...appRoutes].sort(),
        passThroughRoutes: [...passThroughRoutes].sort(),
    };
}

function render({ appRoutes, passThroughRoutes }) {
    const list = (items) => items.map((r) => `    '${r}',`).join('\n');
    return `// AUTO-GENERATED by scripts/generate-route-manifest.mjs — do not edit by hand.
// Source: src/App.tsx (trailRoute paths) + public/_redirects (301/302 sources).

/** Routes the SPA renders. Non-slash requests 301 to the slash form; anything else 404s. */
export const APP_ROUTE_PATTERNS: readonly string[] = [
${list(appRoutes)}
];

/** Routes owned by static redirects or client <Navigate>; the edge function leaves them alone. */
export const PASS_THROUGH_ROUTE_PATTERNS: readonly string[] = [
${list(passThroughRoutes)}
];
`;
}

/** Replace the blanket SPA rewrite with per-route rewrites (Netlify rules ignore trailing slashes). */
export function scopeSpaFallback(redirectsSource, appRoutes) {
    if (!SPA_FALLBACK_RULE.test(redirectsSource)) {
        throw new Error('dist/_redirects has no `/* /index.html 200` rule to replace');
    }
    const rules = appRoutes.map((r) => `${r.replace(/\/$/, '')} /index.html 200`).join('\n');
    return redirectsSource.replace(
        SPA_FALLBACK_RULE,
        `# SPA rewrites scoped to real routes (generated); everything else → 404.html (status 404)\n${rules}`,
    );
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
    const manifest = extractRoutePatterns(
        fs.readFileSync(APP_PATH, 'utf8'),
        fs.readFileSync(REDIRECTS_PATH, 'utf8'),
    );

    if (process.argv.includes('--dist')) {
        const distRedirects = path.join(DIST_DIR, '_redirects');
        fs.copyFileSync(path.join(DIST_DIR, 'index.html'), path.join(DIST_DIR, '404.html'));
        fs.writeFileSync(distRedirects, scopeSpaFallback(fs.readFileSync(distRedirects, 'utf8'), manifest.appRoutes));
        console.log(`✓ dist/404.html + ${manifest.appRoutes.length} scoped SPA rewrites in dist/_redirects`);
        process.exit(0);
    }

    fs.mkdirSync(path.dirname(OUT_PATH), { recursive: true });
    fs.writeFileSync(OUT_PATH, render(manifest));
    console.log(
        `✓ Route manifest: ${manifest.appRoutes.length} app routes, ${manifest.passThroughRoutes.length} pass-through → ${path.relative(ROOT, OUT_PATH)}`,
    );
}
